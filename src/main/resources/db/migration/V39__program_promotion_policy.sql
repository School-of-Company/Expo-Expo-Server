-- 회차별 자동 승급 설정. 두 키가 없으면 기존처럼 promotionEndedAt까지 자동 승급하며 기존 정책은 바꾸지 않는다.
-- autoPromotionEndedAt은 applicationStartedAt 이상 promotionEndedAt 이하이고, 대기 정원 0 회차에는 설정하지 않는다.
CREATE FUNCTION program_promotion_policy_valid(policy JSONB) RETURNS BOOLEAN
    LANGUAGE SQL IMMUTABLE AS $$
SELECT (
    (NOT (policy ? 'autoPromotionEnabled') OR jsonb_typeof(policy -> 'autoPromotionEnabled') = 'boolean')
    AND (NOT (policy ? 'autoPromotionEndedAt') OR (
        jsonb_typeof(policy -> 'autoPromotionEndedAt') = 'string'
        AND COALESCE((policy ->> 'autoPromotionEnabled')::BOOLEAN, TRUE)
        AND (policy ->> 'autoPromotionEndedAt')::TIMESTAMPTZ >= (policy ->> 'applicationStartedAt')::TIMESTAMPTZ
        AND (policy ->> 'autoPromotionEndedAt')::TIMESTAMPTZ <= (policy ->> 'promotionEndedAt')::TIMESTAMPTZ
    ))
    AND ((policy ->> 'waitingCapacity')::BIGINT > 0 OR (
        COALESCE((policy ->> 'autoPromotionEnabled')::BOOLEAN, TRUE) AND NOT (policy ? 'autoPromotionEndedAt')
    ))
) IS TRUE
$$;

ALTER TABLE tb_standard_program ADD CONSTRAINT ck_standard_program_promotion_policy CHECK (
    policy_json IS NULL OR program_promotion_policy_valid(policy_json::jsonb)
);
ALTER TABLE tb_training_program ADD CONSTRAINT ck_training_program_promotion_policy CHECK (
    policy_json IS NULL OR program_promotion_policy_valid(policy_json::jsonb)
);

-- 자동 승급 종료 뒤 관리자 수동 확정 권한. 신청 취소 권한(tb_admin_application_cancel_access)과 별개로 부여한다.
CREATE TABLE tb_admin_application_promote_access (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expo_id VARCHAR(36) NOT NULL REFERENCES tb_expo(id) ON DELETE CASCADE,
    admin_id BIGINT NOT NULL CHECK (admin_id > 0),
    UNIQUE (expo_id, admin_id)
);
