CREATE TABLE tb_expo_member (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expo_id VARCHAR(36) NOT NULL REFERENCES tb_expo(id) ON DELETE CASCADE,
    admin_id BIGINT NOT NULL CHECK (admin_id > 0),
    role VARCHAR(16) NOT NULL CHECK (role IN ('OWNER', 'MANAGER', 'VIEWER')),
    UNIQUE (expo_id, admin_id)
);
CREATE TABLE tb_expo_staff_invite (
    id UUID PRIMARY KEY,
    expo_id VARCHAR(36) NOT NULL REFERENCES tb_expo(id) ON DELETE CASCADE,
    label VARCHAR(100) NOT NULL,
    secret_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ
);
CREATE INDEX ix_expo_member_admin ON tb_expo_member(admin_id);
CREATE INDEX ix_expo_staff_invite_expo ON tb_expo_staff_invite(expo_id);
