-- 박람회 기능 설정(#265, #266). 키 목록과 의존 관계는 코드(ExpoFeatureCatalog)가 가진다.
ALTER TABLE tb_expo ADD COLUMN feature_revision BIGINT NOT NULL DEFAULT 0;

CREATE TABLE tb_expo_feature (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    expo_id VARCHAR(36) NOT NULL REFERENCES tb_expo(id) ON DELETE CASCADE,
    feature_key VARCHAR(64) NOT NULL,
    enabled BOOLEAN NOT NULL,
    UNIQUE (expo_id, feature_key)
);

-- 기존 박람회는 지금처럼 모든 기능을 쓸 수 있게 둔다. 회차·설문·추첨 운영 설정과 전화 인증 값은 건드리지 않는다.
INSERT INTO tb_expo_feature (expo_id, feature_key, enabled)
SELECT expo.id, feature.feature_key, TRUE
FROM tb_expo expo
CROSS JOIN (VALUES
    ('PRE_REGISTRATION'), ('FIELD_REGISTRATION'), ('COMPANION_REGISTRATION'),
    ('QR_ADMISSION'), ('PAPER_QR'),
    ('STANDARD_PROGRAM'), ('TRAINING_PROGRAM'),
    ('STANDARD_ATTENDANCE'), ('TRAINING_ATTENDANCE'),
    ('SURVEY'), ('SURVEY_LOTTERY'),
    ('AUTO_NOTIFICATION'), ('BULK_MESSAGE')
) AS feature(feature_key);
